CREATE TABLE IF NOT EXISTS tb_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(120) NOT NULL UNIQUE,
  nickname VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  creation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_update TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS tb_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(250) NOT NULL,
  description TEXT,
  current_price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (current_price >= 0),
  current_stock INTEGER NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
  status BOOLEAN NOT NULL DEFAULT TRUE,
  creation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_update TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tb_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name TEXT NOT NULL,
  operation VARCHAR(10) NOT NULL CHECK (operation IN ('Create','Read','Update','Delete')),
  db_user TEXT NOT NULL,
  record_id BIGINT,
  description JSONB NOT NULL,
  operation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  operation_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE OR REPLACE FUNCTION fn_update_last_update()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.last_update := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_update_tb_users_timestamp ON tb_users;
CREATE TRIGGER trg_update_tb_users_timestamp
BEFORE UPDATE ON tb_users FOR EACH ROW EXECUTE FUNCTION fn_update_last_update();

DROP TRIGGER IF EXISTS trg_update_tb_products_timestamp ON tb_products;
CREATE TRIGGER trg_update_tb_products_timestamp
BEFORE UPDATE ON tb_products FOR EACH ROW EXECUTE FUNCTION fn_update_last_update();

CREATE OR REPLACE FUNCTION fn_audit_table_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_row JSONB;
  v_operation TEXT;
  v_id BIGINT;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_row := to_jsonb(OLD);
    v_operation := 'Delete';
  ELSIF TG_OP = 'INSERT' THEN
    v_row := to_jsonb(NEW);
    v_operation := 'Create';
  ELSE
    v_row := to_jsonb(NEW);
    v_operation := 'Update';
  END IF;
  v_id := (v_row->>'id')::BIGINT;
  INSERT INTO tb_logs(table_name, operation, db_user, record_id, description)
  VALUES (TG_TABLE_NAME, v_operation, SESSION_USER, v_id, v_row);
  IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_tb_users ON tb_users;
CREATE TRIGGER trg_audit_tb_users
AFTER INSERT OR UPDATE OR DELETE ON tb_users
FOR EACH ROW EXECUTE FUNCTION fn_audit_table_change();

DROP TRIGGER IF EXISTS trg_audit_tb_products ON tb_products;
CREATE TRIGGER trg_audit_tb_products
AFTER INSERT OR UPDATE OR DELETE ON tb_products
FOR EACH ROW EXECUTE FUNCTION fn_audit_table_change();

CREATE OR REPLACE VIEW vw_trazabilidad_productos AS
SELECT p.id, p.sku, p.name, l.db_user AS performed_by,
       l.operation, l.description, l.operation_date
FROM tb_products AS p
JOIN tb_logs AS l ON l.table_name = 'tb_products' AND l.record_id = p.id;

CREATE OR REPLACE VIEW vw_trazabilidad_usuarios AS
SELECT u.id, u.nickname, u.email, l.db_user AS performed_by,
       l.operation, l.description, l.operation_date
FROM tb_users AS u
JOIN tb_logs AS l ON l.table_name = 'tb_users' AND l.record_id = u.id;

